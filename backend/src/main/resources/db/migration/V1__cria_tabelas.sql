CREATE TABLE cliente (
	id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	nome             VARCHAR(255) NOT NULL,
	telefone         VARCHAR(255) NOT NULL UNIQUE,
	dados_informados TEXT
);

CREATE TABLE atendente (
	id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	nome       VARCHAR(255) NOT NULL,
	email      VARCHAR(255) NOT NULL UNIQUE,
	equipe     VARCHAR(255) NOT NULL,
	disponivel BOOLEAN      NOT NULL
);

CREATE TABLE chatbot (
	id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	nome  VARCHAR(255) NOT NULL,
	ativo BOOLEAN      NOT NULL
);

CREATE TABLE conversa (
	id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	cliente_id        BIGINT      NOT NULL REFERENCES cliente (id),
	chatbot_id        BIGINT      REFERENCES chatbot (id),
	atendente_id      BIGINT      REFERENCES atendente (id),
	status            VARCHAR(30) NOT NULL
		CHECK (status IN ('EM_ATENDIMENTO_BOT', 'AGUARDANDO_HUMANO', 'EM_ATENDIMENTO_HUMANO', 'ENCERRADA')),
	assunto           VARCHAR(255),
	equipe            VARCHAR(255),
	entrou_na_fila_em TIMESTAMP,
	versao            BIGINT
);

CREATE INDEX idx_conversa_fila ON conversa (status, entrou_na_fila_em, id);

CREATE TABLE mensagem (
	id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	conversa_id BIGINT      NOT NULL REFERENCES conversa (id),
	conteudo    TEXT        NOT NULL,
	origem      VARCHAR(20) NOT NULL CHECK (origem IN ('CLIENTE', 'BOT', 'ATENDENTE')),
	enviada_em  TIMESTAMP   NOT NULL
);

CREATE INDEX idx_mensagem_conversa ON mensagem (conversa_id);

CREATE TABLE ticket_atendimento (
	id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	protocolo    VARCHAR(255) NOT NULL UNIQUE,
	conversa_id  BIGINT       NOT NULL UNIQUE REFERENCES conversa (id),
	atendente_id BIGINT       NOT NULL REFERENCES atendente (id),
	aberto_em    TIMESTAMP    NOT NULL,
	fechado_em   TIMESTAMP,
	resolucao    VARCHAR(255)
);
